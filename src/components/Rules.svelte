<ol class="rules-list">
  <li>
    Один игрок объясняет слово, остальные угадывают. Слово и однокоренные
    называть нельзя.
  </li>
  <li>
    Угадавшему — <b>+1</b>
    , объясняющему —
    <b>+0,5</b>
    . За пропуск объясняющему —
    <b>−1</b>
    .
  </li>
  <li>
    Нажмите на имя угадавшего. Свайп вверх по слову открывает выбор игрока, вниз
    — пропускает слово.
  </li>
  <li>
    Во время нажатий и выбора игрока таймер остановлен. «Пауза» скрывает слово и
    останавливает ход.
  </li>
  <li>После таймера доиграйте последнее слово без ограничения времени.</li>
  <li>
    Объясняйте по очереди. Побеждает первый, кто набрал выбранное число очков.
  </li>
</ol>
